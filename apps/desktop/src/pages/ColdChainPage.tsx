import React, { useState } from 'react';
import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query';
import {
  LineChart,
  Line,
  XAxis,
  YAxis,
  CartesianGrid,
  Tooltip,
  ResponsiveContainer,
  ReferenceLine
} from 'recharts';
import { Header } from '../components/layout/Header';
import { Card } from '../components/common/Card';
import { Button } from '../components/common/Button';
import { Badge } from '../components/common/Badge';
import { InteractiveRouteMap } from '../components/coldchain/InteractiveRouteMap';
import { api } from '../services/api';
import {
  ThermometerSnowflake,
  Activity,
  AlertTriangle,
  Play,
  Square,
  RefreshCw,
  Radio,
  Sliders,
  CheckCircle2,
  AlertCircle
} from 'lucide-react';

export const ColdChainPage: React.FC = () => {
  const queryClient = useQueryClient();
  const [selectedSensorId, setSelectedSensorId] = useState<string>('');
  const [simMessage, setSimMessage] = useState<string | null>(null);

  const { data: sensorsData } = useQuery({
    queryKey: ['sensors'],
    queryFn: () => api.getSensors()
  });

  const { data: simulatorStatus, refetch: refetchSim } = useQuery({
    queryKey: ['simulator-status'],
    queryFn: () => api.getSimulatorStatus(),
    refetchInterval: 3000
  });

  const sensors = sensorsData?.sensors || [];
  const currentSensorId = selectedSensorId || (sensors.length > 0 ? sensors[0].id : '');
  const activeSensor = sensors.find(s => s.id === currentSensorId);

  const { data: readingsData, refetch: refetchReadings } = useQuery({
    queryKey: ['readings', currentSensorId],
    queryFn: () => api.getReadings({ sensorId: currentSensorId, limit: 30 }),
    enabled: !!currentSensorId,
    refetchInterval: 3000
  });

  // Simulator mutations
  const configMutation = useMutation({
    mutationFn: (config: any) => api.configureSimulator(config),
    onSuccess: (res) => {
      refetchSim();
      setSimMessage(`Simulator mode switched to ${res.mode}`);
      setTimeout(() => setSimMessage(null), 3000);
    }
  });

  const toggleLoopMutation = useMutation({
    mutationFn: (start: boolean) => start ? api.startSimulator() : api.stopSimulator(),
    onSuccess: () => refetchSim()
  });

  const deterministicExcursionMutation = useMutation({
    mutationFn: () =>
      api.emitDeterministicSimulation({
        serialNumber: activeSensor?.serialNumber || 'SNS-COLD-003',
        temperatureCelsius: 11.8,
        isExcursion: true
      }),
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['readings'] });
      queryClient.invalidateQueries({ queryKey: ['alerts'] });
      setSimMessage('Test excursion (11.8°C) injected successfully! Alert generated.');
      setTimeout(() => setSimMessage(null), 4000);
    }
  });

  const readings = (readingsData?.readings || []).slice().reverse().map((r: any) => ({
    time: new Date(r.timestamp).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit' }),
    temperature: r.temperatureCelsius,
    isExcursion: r.isExcursion
  }));

  const latestReading = readingsData?.readings?.[0];
  const minBound = activeSensor?.serialNumber === 'SNS-COLD-001' ? -90 : 2;
  const maxBound = activeSensor?.serialNumber === 'SNS-COLD-001' ? -60 : 8;

  return (
    <div>
      <Header
        title="Cold-Chain Monitoring & IoT Telemetry"
        subtitle="Real-time thermal monitoring across ultra-cold vaults and transport reefers"
        action={
          <div className="flex items-center gap-2">
            <Button
              variant="outline"
              size="sm"
              leftIcon={<RefreshCw className="w-4 h-4" />}
              onClick={() => {
                refetchReadings();
                refetchSim();
              }}
            >
              Refresh Stream
            </Button>
          </div>
        }
      />

      <div className="p-6 max-w-7xl mx-auto space-y-6">
        {/* Notice of Simulation Segment */}
        <div className="p-4 rounded-xl bg-amber-50 border-2 border-slate-900 flex items-center justify-between shadow-2xs">
          <div className="flex items-center gap-3">
            <div className="p-2 rounded-lg bg-amber-500 text-white border-2 border-slate-900 shadow-xs">
              <Radio className="w-5 h-5" />
            </div>
            <div>
              <h4 className="text-sm font-bold text-navy-900">Simulated IoT Telemetry Mode</h4>
              <p className="text-xs text-slate-700 font-medium">
                All sensor streams displayed below are generated by the configurable cold-chain simulator and strictly labelled <code className="bg-amber-100 border border-amber-300 px-1 py-0.5 rounded font-mono font-semibold">isSimulated: true</code>.
              </p>
            </div>
          </div>
          <Badge variant="amber">SIMULATED DATA</Badge>
        </div>

        {simMessage && (
          <div className="p-3.5 rounded-xl bg-teal-50 border-2 border-slate-900 text-teal-900 text-xs flex items-center gap-2 shadow-2xs">
            <CheckCircle2 className="w-4 h-4 shrink-0 text-teal-600" />
            <span className="font-semibold">{simMessage}</span>
          </div>
        )}

        {/* Live GPS Supply-Chain Corridors & Thermal Radar Map */}
        <InteractiveRouteMap />

        {/* Top Control Bar: Sensor Picker & Simulator Controller */}
        <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
          {/* Active Sensor Selector */}
          <Card title="Telemetry Sensor Selector" subtitle="Select probe or stationary cold hub">
            <div className="space-y-3">
              <select
                value={currentSensorId}
                onChange={(e) => setSelectedSensorId(e.target.value)}
                className="w-full px-3 py-2 text-xs bg-white border-2 border-slate-900 rounded-xl focus:outline-none focus:ring-2 focus:ring-teal font-bold text-navy-900 shadow-2xs"
              >
                {sensors.map(s => (
                  <option key={s.id} value={s.id}>
                    {s.serialNumber} — {s.name} ({s.location})
                  </option>
                ))}
              </select>

              {activeSensor && (
                <div className="p-3.5 rounded-xl bg-slate-50 border-2 border-slate-900 space-y-1.5 text-xs shadow-2xs">
                  <div className="flex justify-between">
                    <span className="text-slate-600 font-medium">Sensor Serial:</span>
                    <span className="font-mono font-bold text-navy-900">{activeSensor.serialNumber}</span>
                  </div>
                  <div className="flex justify-between">
                    <span className="text-slate-600 font-medium">Location:</span>
                    <span className="text-navy-900 font-semibold">{activeSensor.location}</span>
                  </div>
                  <div className="flex justify-between">
                    <span className="text-slate-600 font-medium">Battery Level:</span>
                    <span className="font-mono text-emerald-700 font-bold">{activeSensor.batteryLevel}%</span>
                  </div>
                  <div className="flex justify-between">
                    <span className="text-slate-600 font-medium">Permitted Safe Threshold:</span>
                    <span className="font-mono font-bold text-teal-dark">{minBound}°C to {maxBound}°C</span>
                  </div>
                </div>
              )}
            </div>
          </Card>

          {/* Current Reading Hero Card */}
          <Card
            title="Live Reading Metric"
            subtitle="Latest recorded temperature from probe"
            headerAction={
              <div className="flex items-center gap-1.5 px-2 py-0.5 rounded-full bg-emerald-50 border border-emerald-200 text-[10px] font-bold text-emerald-700">
                <span className="w-2 h-2 rounded-full bg-emerald-500 animate-beacon" />
                <span>STREAM ACTIVE</span>
              </div>
            }
          >
            <div className="flex flex-col items-center justify-center py-2 relative">
              <div className="flex items-baseline gap-1 relative">
                <span className={`text-4xl font-extrabold font-mono transition-colors duration-300 ${latestReading?.isExcursion ? 'text-status-red' : 'text-teal-dark'}`}>
                  {latestReading ? `${latestReading.temperatureCelsius}°C` : '--'}
                </span>
                <span className="inline-block w-2.5 h-2.5 rounded-full bg-teal animate-ping absolute -right-3 top-0 opacity-75" />
              </div>

              <div className="mt-3 flex items-center gap-2">
                <Badge variant={latestReading?.isExcursion ? 'red' : 'green'} className={latestReading?.isExcursion ? 'animate-pulse' : ''}>
                  {latestReading?.isExcursion ? 'EXCURSION DETECTED' : 'WITHIN THRESHOLD'}
                </Badge>
                <Badge variant="gray">
                  {latestReading ? new Date(latestReading.timestamp).toLocaleTimeString() : 'Awaiting stream'}
                </Badge>
              </div>

              <p className="text-[11px] text-navy-700 mt-3 text-center">
                Permitted range: {minBound}°C to {maxBound}°C
              </p>
            </div>
          </Card>

          {/* IoT Simulator Control Deck */}
          <Card
            title="IoT Simulator Controls"
            subtitle="Test cold-chain anomalies & hardware disconnections"
            headerAction={
              <Badge variant={simulatorStatus?.isRunning ? 'green' : 'gray'}>
                {simulatorStatus?.isRunning ? 'Simulator Running' : 'Paused'}
              </Badge>
            }
          >
            <div className="space-y-3 text-xs">
              <div className="flex items-center justify-between">
                <span className="font-semibold text-navy-900">Simulation Scenario:</span>
                <span className="font-mono font-bold text-teal">{simulatorStatus?.simulationMode || 'NORMAL'}</span>
              </div>

              {/* Mode Buttons */}
              <div className="grid grid-cols-3 gap-2">
                <button
                  onClick={() => configMutation.mutate({ mode: 'NORMAL' })}
                  className="px-2.5 py-1.5 rounded-lg border-2 border-slate-900 bg-white hover:bg-emerald-50 font-bold text-emerald-800 transition-colors shadow-2xs"
                >
                  Normal
                </button>
                <button
                  onClick={() => configMutation.mutate({ mode: 'EXCURSION' })}
                  className="px-2.5 py-1.5 rounded-lg border-2 border-slate-900 bg-white hover:bg-red-50 font-bold text-red-700 transition-colors shadow-2xs"
                >
                  Excursion
                </button>
                <button
                  onClick={() => configMutation.mutate({ mode: 'DISCONNECTED' })}
                  className="px-2.5 py-1.5 rounded-lg border-2 border-slate-900 bg-white hover:bg-slate-100 font-bold text-slate-800 transition-colors shadow-2xs"
                >
                  Disconnect
                </button>
              </div>

              {/* Start / Stop and Inject Button */}
              <div className="pt-2 border-t border-surface-border flex items-center justify-between">
                <Button
                  variant="outline"
                  size="sm"
                  leftIcon={simulatorStatus?.isRunning ? <Square className="w-3.5 h-3.5" /> : <Play className="w-3.5 h-3.5" />}
                  onClick={() => toggleLoopMutation.mutate(!simulatorStatus?.isRunning)}
                >
                  {simulatorStatus?.isRunning ? 'Pause Ticker' : 'Resume Ticker'}
                </Button>

                <Button
                  variant="danger"
                  size="sm"
                  leftIcon={<AlertTriangle className="w-3.5 h-3.5" />}
                  isLoading={deterministicExcursionMutation.isPending}
                  onClick={() => deterministicExcursionMutation.mutate()}
                >
                  Inject Spike
                </Button>
              </div>
            </div>
          </Card>
        </div>

        {/* Real-Time Temperature Chart */}
        <Card
          title="Telemetry Thermal History Chart"
          subtitle={`Time-series trajectory for ${activeSensor?.name || 'Selected Unit'} (Safe Bound: ${minBound}°C to ${maxBound}°C)`}
        >
          {readings.length === 0 ? (
            <div className="h-64 flex items-center justify-center text-xs text-navy-700">
              Awaiting telemetry readings from simulator...
            </div>
          ) : (
            <div className="h-72 w-full pt-4">
              <ResponsiveContainer width="100%" height="100%">
                <LineChart data={readings} margin={{ top: 10, right: 30, left: 0, bottom: 0 }}>
                  <CartesianGrid strokeDasharray="3 3" stroke="#e2e8f0" />
                  <XAxis dataKey="time" stroke="#64748b" fontSize={11} />
                  <YAxis stroke="#64748b" fontSize={11} domain={['auto', 'auto']} unit="°C" />
                  <Tooltip
                    contentStyle={{ backgroundColor: '#0f172a', borderColor: '#334155', borderRadius: '4px', color: '#fff', fontSize: '11px' }}
                    labelStyle={{ color: '#94a3b8' }}
                  />
                  {/* Reference lines for safe boundaries */}
                  <ReferenceLine y={maxBound} stroke="#ef4444" strokeDasharray="4 4" label={{ value: `Max Safe: ${maxBound}°C`, fill: '#ef4444', fontSize: 10 }} />
                  <ReferenceLine y={minBound} stroke="#0284c7" strokeDasharray="4 4" label={{ value: `Min Safe: ${minBound}°C`, fill: '#0284c7', fontSize: 10 }} />
                  <Line
                    type="monotone"
                    dataKey="temperature"
                    stroke="#0d9488"
                    strokeWidth={2}
                    dot={{ fill: '#0d9488', r: 3 }}
                    activeDot={{ r: 5 }}
                    isAnimationActive={false}
                  />
                </LineChart>
              </ResponsiveContainer>
            </div>
          )}
        </Card>
      </div>
    </div>
  );
};
